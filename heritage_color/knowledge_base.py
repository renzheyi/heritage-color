def get_material(name: str):
    """按名称取材质，支持模糊包含匹配。"""
    if name in MATERIALS:
        return MATERIALS[name]
    hits = [m for n, m in MATERIALS.items() if name in n]
    if len(hits) == 1:
        return hits[0]
    return None
