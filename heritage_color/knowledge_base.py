def get_pigment(name: str):
    """按名称取颜料，支持模糊包含匹配（如『朱』->朱砂）。"""
    if name in PIGMENTS:
        return PIGMENTS[name]
    hits = [p for n, p in PIGMENTS.items() if name in n]
    if len(hits) == 1:
        return hits[0]
    return None


